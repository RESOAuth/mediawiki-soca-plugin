<?php
declare(strict_types=1);
use MediaWiki\Extension\SOCA\{Configuration, Service, Store};
use MediaWiki\MediaWikiServices;
use RESOAuth\Soca\Failure;
$assertions = 0;
$assert = static function (bool $result, string $message) use (&$assertions): void { $assertions++; if (!$result) { throw new RuntimeException($message); } };
$reject = static function (callable $fn, string $message) use ($assert): void { try { $fn(); } catch (Failure $e) { $assert(true, $message); return; } $assert(false, $message); };
$service = new Service(); $store = $service->store; $services = MediaWikiServices::getInstance();
$config = $service->configuration->effective();
$issuer = $config['issuer']; $subject = 'integration-' . bin2hex(random_bytes(8));
$store->ledger('state-' . $subject, 'browser-original');
$reject(fn() => $store->consume('state-' . $subject, 'browser-other'), 'Copied callback must fail');
$store->consume('state-' . $subject, 'browser-original');
$reject(fn() => $store->consume('state-' . $subject, 'browser-original'), 'Replayed callback must fail');
$person = $services->getUserFactory()->newFromName('Local ' . bin2hex(random_bytes(6)));
$person->setEmail('same@example.com'); $assert($person->addToDatabase()->isGood(), 'Create local fixture');
$reject(fn() => $service->resolve(['sub' => $subject, 'email' => 'same@example.com', 'email_verified' => true], $config), 'Email never selects unlinked account');
$store->link($issuer, $subject, $person->getId());
$assert($store->linked($issuer, $subject) === $person->getId(), 'Unique issuer/subject association');
$reject(fn() => $store->link($issuer, $subject, $person->getId()), 'Duplicate link denied');
$returning = $service->resolve(['sub' => $subject, 'email' => 'changed@example.com'], $config);
$assert($returning->getId() === $person->getId() && $returning->getEmail() === 'same@example.com', 'Returning identity preserves local profile');
$newSubject = 'provision-' . bin2hex(random_bytes(8));
$new = $service->resolve(['sub' => $newSubject, 'email' => 'new@example.com', 'name' => 'New Person'], array_replace($config, ['provision' => true]));
$assert($new->isRegistered() && $new->getId() !== $person->getId(), 'Provisioned native local account');
$assert($store->linked($issuer, $newSubject) === $new->getId(), 'Provisioning links in transaction');
$assert(!array_intersect($services->getUserGroupManager()->getUserGroups($new), ['sysop', 'bureaucrat', 'interface-admin']), 'No privileged group grants');
$assert($service->resolve(['sub' => $newSubject], $config)->getId() === $new->getId(), 'Returning new account stable');
$badSubject = 'rollback-' . bin2hex(random_bytes(8));
$reject(fn() => $service->resolve(['sub' => $badSubject, 'email' => 'new@example.com', 'name' => '<script>'], array_replace($config, ['provision' => true])), 'Invalid claims rejected');
$assert($store->linked($issuer, $badSubject) === null, 'No orphaned link after failure');
$name = 'SOCA ' . substr(Store::identityKey($issuer, $badSubject), 0, 32);
$assert(!$services->getUserFactory()->newFromName($name)->isRegistered(), 'No orphaned user after failure');
$row = $store->settings('integration:cas');
$store->save('integration:cas', ['first' => true], $row['revision']);
$reject(fn() => $store->save('integration:cas', ['stale' => true], $row['revision']), 'Stale configuration rejected');
$configuration = $service->configuration; $client = $configuration->client();
$candidate = $store->settings()['value']; $candidate['enabled'] = true;
$reject(fn() => $configuration->save($candidate, $store->settings()['revision']), 'Activation requires real candidate evidence');
$nativeSession = RequestContext::getMain()->getRequest()->getSession();
$abandoned = RESOAuth\Soca\Json::b64(random_bytes(32)); $abandonedKey = hash('sha256', $abandoned);
$nativeSession->setSecret('SOCA.tx.' . $abandonedKey, ['verifier' => 'abandoned-secret']);
$nativeSession->set('SOCA.transactions', [$abandonedKey => time() - 301]);
$reject(fn() => $service->begin($nativeSession, false), 'Disabled profile still rejects a new login after cleanup');
$assert($nativeSession->getSecret('SOCA.tx.' . $abandonedKey) === null && $nativeSession->get('SOCA.transactions') === [], 'Expired encrypted transaction payloads pruned before another start');
$expired = RESOAuth\Soca\Json::b64(random_bytes(32)); $expiredKey = hash('sha256', $expired);
$nativeSession->setSecret('SOCA.browser', 'native-test-browser');
$nativeSession->setSecret('SOCA.tx.' . $expiredKey, ['verifier' => 'expired-secret']);
$nativeSession->set('SOCA.transactions', [$expiredKey => time() - 301]);
$store->ledger($expired, 'native-test-browser', -1);
$reject(fn() => $service->callback($nativeSession, ['state' => $expired], 0), 'Expired callback cannot consume expired ledger');
$assert($nativeSession->getSecret('SOCA.tx.' . $expiredKey) === null && $nativeSession->get('SOCA.transactions') === [], 'Expired callback deletes encrypted payload even when ledger consumption fails');
putenv('SOCA_EMERGENCY_DISABLE=1');
$assert(Configuration::emergency(), 'Deployment emergency override');
$reject(fn() => $service->begin(RequestContext::getMain()->getRequest()->getSession(), true, $person->getId()), 'Emergency blocks test login');
putenv('SOCA_EMERGENCY_DISABLE');
$adminContext = new RequestContext();
$adminContext->setUser($services->getUserFactory()->newFromName('Admin'));
$adminContext->setTitle(MediaWiki\Title\Title::newFromText('Special:SOCA'));
$settingsPage = new MediaWiki\Extension\SOCA\SpecialSOCA();
$settingsPage->setContext($adminContext); $settingsPage->execute('');
$html = $adminContext->getOutput()->getHTML();
$assert(str_contains($html, 'name="token"') && str_contains($html, 'soca_action'), 'Native administrator settings and CSRF form');
$assert(str_contains($html, 'metadata_mode') && str_contains($html, 'readonly') && str_contains($html, 'Candidate status'), 'Deployment settings locked and candidate status visible');
echo "MediaWiki native integration: $assertions assertions passed.\n";
